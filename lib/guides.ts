export const GUIDE_BY_SLUG = new Map(GUIDES.map((g) => [g.slug, g]))

/**
 * 이 치과의 상세 페이지에 붙일 가이드 3개를 고른다.
 *
 * 조건에 맞는 글을 먼저 넣고, 남는 자리는 치과 id 로 회전시켜 채운다.
 * 전 페이지가 같은 3개를 링크하지 않게 하려는 것이다.
 */
export function pickGuidesFor(clinic: {
  id: number
  category: string | null
  open_night: boolean
  open_sunday: boolean
  open_holiday: boolean
  hours: Record<string, string>
}): Guide[] {
  const picked: Guide[] = []
  const add = (slug: string) => {
    const guide = GUIDE_BY_SLUG.get(slug)
    if (guide && !picked.some((p) => p.slug === guide.slug)) picked.push(guide)
  }

  if (clinic.open_night || clinic.open_sunday || clinic.open_holiday) {
    add("schedule")
  }
  if (clinic.category === "치과병원") {
    add("clinic-types")
  }
  if (Object.keys(clinic.hours ?? {}).length === 0) {
    // 진료시간조차 공개되지 않은 곳이라 '무엇을 물어볼지'가 더 쓸모 있다.
    add("choosing")
  }

  // 나머지는 id 기준 회전. 같은 치과는 항상 같은 결과가 나온다.
  const rest = GUIDES.filter((g) => !picked.some((p) => p.slug === g.slug))
  const offset = Math.abs(clinic.id) % Math.max(rest.length, 1)
  for (let i = 0; picked.length < 3 && i < rest.length; i++) {
    picked.push(rest[(offset + i) % rest.length])
  }

  return picked.slice(0, 3)
}
